package com.lecook.backend;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import javax.sql.DataSource;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
class LegacyMigrationTests extends IsolatedDatabase {
    @Autowired DataSource dataSource;

    @Test void adoptsLegacyTablesWithoutRemovingRecipes() {
        var schema = "lecook_legacy_test_" + UUID.randomUUID().toString().replace("-", "");
        var jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE SCHEMA " + schema);
        try {
            jdbc.execute("CREATE TABLE " + schema + ".categories (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255))");
            jdbc.execute("CREATE TABLE " + schema + ".recipes (id UUID PRIMARY KEY, name VARCHAR(255), description VARCHAR(255), image_url VARCHAR(255), calories INTEGER, category_id INTEGER REFERENCES " + schema + ".categories(id), created_at TIMESTAMP, updated_at TIMESTAMP)");
            var id = UUID.randomUUID();
            jdbc.update("INSERT INTO " + schema + ".recipes (id,name,description,calories) VALUES (?,?,?,?)", id, "Збережений борщ", "Старий опис", 200);
            Flyway.configure().dataSource(dataSource).schemas(schema).defaultSchema(schema)
                .baselineOnMigrate(true).baselineVersion("0").load().migrate();
            assertEquals("Збережений борщ", jdbc.queryForObject("SELECT name FROM " + schema + ".recipes WHERE id=?", String.class, id));
            jdbc.update("UPDATE " + schema + ".recipes SET description=? WHERE id=?", "Кроки ".repeat(500), id);
            assertEquals(3000, jdbc.queryForObject("SELECT length(description) FROM " + schema + ".recipes WHERE id=?", Integer.class, id));
        } finally {
            if (!schema.matches("lecook_legacy_test_[0-9a-f]{32}")) throw new IllegalStateException("Unexpected test schema");
            jdbc.execute("DROP SCHEMA " + schema + " CASCADE");
        }
    }
}
